const storage = {
    get(k) { try { return localStorage.getItem(k); } catch { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch { /* ignorar */ } },
};

let currentLang = storage.get('lang') || 'es';
if (!translations[currentLang]) currentLang = 'es';

export function t(key, params = {}) {
    let text = translations[currentLang][key] ?? translations.es[key] ?? key;
    for (const [k, v] of Object.entries(params)) text = text.replaceAll('{' + k + '}', v);
    return text;
}
export const tItem = id => translations[currentLang].items[id] ?? id;
export const getLang = () => currentLang;

export function setLang(lang, onChange) {
    if (!translations[lang]) return;
    currentLang = lang;
    storage.set('lang', lang);
    document.documentElement.lang = lang;
    document.title = t(document.body.dataset.titleKey || 'title');

    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('[data-lang]').forEach(btn => {
        const activo = btn.dataset.lang === lang;
        btn.classList.toggle('active', activo);
        btn.setAttribute('aria-pressed', String(activo));
    });

    if (onChange) onChange();
}

